const PAR_CODE: ReadonlyMap<string, CategorieJuridique> = new Map(CATEGORIES_JURIDIQUES.map((c) => [c.code, c]))

/** La catégorie juridique d'un code, ou null quand la nomenclature ne le connaît pas (à la lettre près). */
export function categorieJuridique(code: string): CategorieJuridique | null {
  return PAR_CODE.get(code) ?? null
}
